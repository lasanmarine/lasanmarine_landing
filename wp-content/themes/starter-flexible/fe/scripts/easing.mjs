/**
 * Builds src/styles/_easing.scss: the site's motion curves as CSS custom
 * properties, computed from spring physics (src/lib/motion-math.js) and
 * written as `linear()` easings. Run by `npm run build` (prebuild).
 *
 * A spring is described by how long it takes to settle and how much it
 * bounces; the curve is the exact closed-form response of a damped
 * oscillator, sampled and reduced to a few dozen stops (RDP, ≤ 0.002 error).
 * Browsers without `linear()` keep the cubic-bezier fallbacks.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { springEasing } from '../src/lib/motion-math.js';

const out = join(dirname(fileURLToPath(import.meta.url)), '../src/styles/_easing.scss');

// name: [settle seconds, bounce, launch, fallback, what it is for]
// launch = initial velocity / ω₀ (0: from rest, 1: flicked).
const curves = {
	ease: [0.9, 0, 0.7, 'cubic-bezier(0.22, 1, 0.36, 1)', 'default: critically damped, gently launched, no overshoot'],
	'spring-out': [0.9, 0, 1, 'cubic-bezier(0.16, 1, 0.3, 1)', 'entrances (reveal): launched, so it arrives fast and settles softly'],
	'spring-soft': [0.6, 0.18, 0, 'cubic-bezier(0.34, 1.3, 0.64, 1)', 'things the pointer moves: from rest, a small damped overshoot'],
	'spring-snappy': [0.38, 0, 1, 'cubic-bezier(0.2, 0.9, 0.3, 1)', 'small UI: menus, panels, accordions'],
};

let fallback = '';
let modern = '';
for (const [name, [settle, bounce, launch, bez, note]] of Object.entries(curves)) {
	const { easing, duration } = springEasing(settle, bounce, { launch });
	fallback += `\t/* ${note} */\n\t--${name}: ${bez};\n\t--${name}-ms: ${duration}ms;\n`;
	modern += `\t\t--${name}: ${easing};\n`;
}

writeFileSync(
	out,
	`/* Generated by scripts/easing.mjs from spring physics — do not edit by hand. */
:root {
${fallback}}
@supports (transition-timing-function: linear(0, 1)) {
	:root {
${modern}	}
}
`,
);
console.log(`easing: ${Object.keys(curves).length} curves → ${out}`);
