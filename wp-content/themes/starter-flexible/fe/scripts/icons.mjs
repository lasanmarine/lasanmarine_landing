/**
 * Builds inc/icon-paths.php from Heroicons (24px outline). The theme keeps its
 * own icon keys — content stored in the database refers to them — and each key
 * points at the Heroicon that stands in for it. The PHP file is generated but
 * committed, because the server runs without node_modules.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const outline = join(dirname(require.resolve('heroicons/package.json')), '24/outline');
const out = join(dirname(fileURLToPath(import.meta.url)), '../../inc/icon-paths.php');

const icons = {
	arrow: 'arrow-right',
	arrowUpRight: 'arrow-up-right',
	arrowLeft: 'arrow-left',
	arrowUp: 'arrow-up',
	arrowDown: 'arrow-down',
	chevronLeft: 'chevron-left',
	chevronRight: 'chevron-right',
	chevronDown: 'chevron-down',
	sort: 'chevron-up-down',
	download: 'arrow-down-tray',
	file: 'document',
	phone: 'phone',
	mail: 'envelope',
	pin: 'map-pin',
	ship: 'lifebuoy',
	waves: 'cube-transparent',
	ruler: 'cog-6-tooth',
	link: 'link',
	scan: 'viewfinder-circle',
	wrench: 'wrench-screwdriver',
	compass: 'globe-asia-australia',
	award: 'check-badge',
	check: 'check-circle',
	close: 'x-mark',
	plus: 'plus',
	calculator: 'calculator',
	copy: 'document-duplicate',
	gauge: 'bolt',
	search: 'magnifying-glass',
	calendar: 'calendar',
	clock: 'clock',
	user: 'user',
	share: 'share',
	tag: 'tag',
	book: 'book-open',
};

const rows = Object.entries(icons).map(([key, hero]) => {
	const svg = readFileSync(join(outline, `${hero}.svg`), 'utf8');
	const inner = svg
		.replace(/^[\s\S]*?<svg[^>]*>/, '')
		.replace(/<\/svg>\s*$/, '')
		.replace(/\s*\n\s*/g, '')
		// The <svg> wrapper in inc/icons.php sets these for every icon.
		.replace(/\s+stroke-line(cap|join)="round"/g, '');
	return `\t'${key}' => '${inner.replace(/'/g, "\\'")}', // ${hero}`;
});

writeFileSync(
	out,
	`<?php
/**
 * Icon paths — GENERATED by fe/scripts/icons.mjs from Heroicons (outline, 24px).
 * Do not edit by hand: change the map in the script and run \`npm run icons\`.
 *
 * @package Starter_Flexible
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

return array(
${rows.join('\n')}
);
`
);
console.log(`icons: ${rows.length} written to inc/icon-paths.php`);
